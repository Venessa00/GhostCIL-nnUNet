#!/usr/bin/env python3
"""Register the custom trainers with nnU-Net v2.

nnU-Net locates trainers by class name inside the ``nnunetv2.training.nnUNetTrainer``
package (``recursive_find_python_class``). A small shim module placed in its
``variants/`` folder imports our classes, so that ``-tr <ClassName>`` works while the
code stays in the ``ghostcil_nnunet`` package. Re-run this script after upgrading
nnU-Net.
"""
import sys
from pathlib import Path

SHIM = '''"""Generated by scripts/install_trainers.py of GhostCIL-nnUNet; do not edit."""
from ghostcil_nnunet.trainers import (  # noqa: F401
    nnUNetTrainerBaseline150,
    nnUNetTrainerGhostCIL,
    nnUNetTrainerGhostCIL_MDA,
    nnUNetTrainerGMA,
    nnUNetTrainerGMA_DiceOnly,
    nnUNetTrainerGMA_DiceFocal,
    nnUNetTrainerGMA_DiceBoundary,
    nnUNetTrainerGMA_NoFreq,
    nnUNetTrainerUNet,
    nnUNetTrainerAttUNet,
    nnUNetTrainerExtModel,
)
'''


def main():
    try:
        import nnunetv2
    except ImportError:
        sys.exit("nnunetv2 is not installed: pip install nnunetv2")
    try:
        import ghostcil_nnunet  # noqa: F401
    except ImportError:
        sys.exit("ghostcil_nnunet is not installed: run 'pip install -e .' in the repository root")

    variants = Path(nnunetv2.__file__).parent / "training" / "nnUNetTrainer" / "variants"
    if not variants.is_dir():
        sys.exit(f"{variants} not found; unsupported nnU-Net version")

    target = variants / "ghostcil_trainers.py"
    target.write_text(SHIM, encoding="utf-8")
    print(f"wrote {target}")

    # Verify that nnU-Net can find every trainer
    from nnunetv2.utilities.find_class_by_name import recursive_find_python_class
    import nnunetv2.training.nnUNetTrainer as tr_pkg
    names = ["nnUNetTrainerBaseline150", "nnUNetTrainerGhostCIL",
             "nnUNetTrainerGhostCIL_MDA", "nnUNetTrainerGMA",
             "nnUNetTrainerGMA_DiceOnly", "nnUNetTrainerGMA_DiceFocal",
             "nnUNetTrainerGMA_DiceBoundary", "nnUNetTrainerGMA_NoFreq",
             "nnUNetTrainerUNet", "nnUNetTrainerAttUNet", "nnUNetTrainerExtModel"]
    ok = True
    for n in names:
        cls = recursive_find_python_class(Path(tr_pkg.__file__).parent, n,
                                          "nnunetv2.training.nnUNetTrainer")
        print(("  ok  " if cls else "  MISSING  ") + n)
        ok = ok and cls is not None
    if not ok:
        sys.exit("some trainers were not found; check that ghostcil_nnunet is installed")
    print("all trainers registered")


if __name__ == "__main__":
    main()
